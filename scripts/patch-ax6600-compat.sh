#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="${1:?OpenWrt source directory required}"
PACKAGES="$ROOT/feeds/packages"

# libtirpc 1.3.7 includes the obsolete sys/poll.h from rtime.c.
# musl redirects it with a warning; use the standard POSIX poll.h header.
test -d "$PACKAGES/libs/libtirpc" || {
  echo "Expected package directory missing: $PACKAGES/libs/libtirpc" >&2
  exit 1
}
mkdir -p "$PACKAGES/libs/libtirpc/patches"
cat > "$PACKAGES/libs/libtirpc/patches/100-musl-poll-header.patch" <<'PATCH'
--- a/src/rtime.c
+++ b/src/rtime.c
@@ -49 +49 @@
-#include <sys/poll.h>
+#include <poll.h>
PATCH

# Do not patch udns here: its source layout is generated by the feed's
# autotools patch and the previous guessed hunk did not match udns 0.7.
# Keep the upstream package intact; its compatibility warning is non-fatal.

# elfutils has separate host-tool and target-package builds. Patch both
# locations when present so the gettext_noop fallback is guarded in each.
for base in "$ROOT/tools/elfutils" "$ROOT/package/libs/elfutils"; do
  if [ -d "$base" ]; then
    dir="$base/patches"
    mkdir -p "$dir"
    cat > "$dir/102-guard-gettext-noop.patch" <<'PATCH'
--- a/lib/system.h
+++ b/lib/system.h
@@ -162 +162,3 @@
-#define gettext_noop(Str) Str
+#ifndef gettext_noop
+#define gettext_noop(Str) Str
+#endif
PATCH
  fi
done

echo "Applied AX6600 compatibility patches: libtirpc poll header and elfutils gettext macro guard."
